/**
 * Fetches real road geometry for every corridor leg from OSRM and writes it to
 * lib/corridor-routes.ts, so the site ships the lines rather than calling a
 * routing service in the browser.
 *
 * Run with: node scripts/build-corridor-routes.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const OSRM = "https://router.project-osrm.org/route/v1/driving";
/**
 * A road route this much longer than the crow line is not a road route.
 * Real detours here top out around 2.2x (Siem Reap to Battambang, which has to
 * go around the Tonle Sap); genuine sea and mountain crossings come back 4x or
 * worse, so 3 separates them cleanly.
 */
const DETOUR_LIMIT = 3;

function haversine(a, b) {
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.sin(dLng / 2) ** 2 *
      Math.cos(toRad(a[0])) *
      Math.cos(toRad(b[0]));
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

/** Drops points that barely change the shape, to keep the payload small. */
function decimate(coords, max = 140) {
  if (coords.length <= max) return coords;
  const step = Math.ceil(coords.length / max);
  const out = coords.filter((_, i) => i % step === 0);
  const last = coords[coords.length - 1];
  if (out[out.length - 1] !== last) out.push(last);
  return out;
}

const source = readFileSync("lib/data.ts", "utf8");
const arrayStart = source.indexOf("export const corridors: Corridor[] = [");
// Stop at the close of the array — mapDestinations below it matches the same
// slug/name shape and would otherwise be picked up as corridors.
const block = source.slice(arrayStart, source.indexOf("\n];", arrayStart));

// Pull slug + stop coordinates straight out of the data file.
const corridors = [];
for (const m of block.matchAll(/slug: "([a-z-]+)",\n    name: "([^"]+)"/g)) {
  corridors.push({ slug: m[1], name: m[2], index: m.index, stops: [] });
}
for (let i = 0; i < corridors.length; i++) {
  const from = corridors[i].index;
  const to = i + 1 < corridors.length ? corridors[i + 1].index : block.length;
  const slice = block.slice(from, to);
  for (const s of slice.matchAll(
    /\{ name: "([^"]+)",[^}]*?lat: (-?[\d.]+), lng: (-?[\d.]+) \}/g,
  )) {
    corridors[i].stops.push({
      name: s[1],
      lat: Number(s[2]),
      lng: Number(s[3]),
    });
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const out = [];

for (const corridor of corridors) {
  const legs = [];

  for (let i = 0; i < corridor.stops.length - 1; i++) {
    const a = corridor.stops[i];
    const b = corridor.stops[i + 1];
    const direct = haversine([a.lat, a.lng], [b.lat, b.lng]);

    let coords = null;
    let km = null;

    try {
      const url = `${OSRM}/${a.lng},${a.lat};${b.lng},${b.lat}?overview=full&geometries=geojson`;
      const res = await fetch(url, { signal: AbortSignal.timeout(30000) });
      const json = await res.json();
      if (json.code === "Ok" && json.routes?.[0]) {
        km = json.routes[0].distance / 1000;
        coords = json.routes[0].geometry.coordinates.map(([lng, lat]) => [
          lat,
          lng,
        ]);
      }
    } catch (error) {
      console.warn(`  ! ${a.name} -> ${b.name}: ${error.message}`);
    }

    const detour = km && direct ? km / direct : Infinity;
    const isRoad = coords && detour <= DETOUR_LIMIT;

    console.log(
      `  ${corridor.slug}: ${a.name} -> ${b.name} | direct ${direct.toFixed(0)}km` +
        (km ? ` road ${km.toFixed(0)}km (x${detour.toFixed(1)})` : " no route") +
        ` => ${isRoad ? "road" : "boat/direct"}`,
    );

    legs.push({
      from: a.name,
      to: b.name,
      mode: isRoad ? "road" : "direct",
      km: Math.round((isRoad ? km : direct) * 10) / 10,
      coords: isRoad
        ? decimate(coords).map(([lat, lng]) => [
            Math.round(lat * 1e4) / 1e4,
            Math.round(lng * 1e4) / 1e4,
          ])
        : [
            [a.lat, a.lng],
            [b.lat, b.lng],
          ],
    });

    await sleep(1200);
  }

  out.push({ slug: corridor.slug, legs });
}

const file = `// Generated by scripts/build-corridor-routes.mjs — do not edit by hand.
//
// Road geometry for each corridor leg, fetched from OSRM (OpenStreetMap data)
// at build time. Legs marked "direct" have no drivable route — island and
// lake crossings — and are drawn as a dashed straight line instead.

export type CorridorLeg = {
  from: string;
  to: string;
  mode: "road" | "direct";
  km: number;
  coords: [number, number][];
};

export const corridorRoutes: Record<string, CorridorLeg[]> = ${JSON.stringify(
  Object.fromEntries(out.map((c) => [c.slug, c.legs])),
  null,
  2,
)};
`;

writeFileSync("lib/corridor-routes.ts", file);
console.log(`\nWrote lib/corridor-routes.ts (${(file.length / 1024).toFixed(0)} KB)`);
